// Merge all sub-dictionaries into main TRANSLATIONS
const ALL_SUB_DICTS = [
  HABITAT_TRANSLATIONS,
  INTELLIGENCE_TRANSLATIONS,
  LICENSING_TRANSLATIONS,
  PASSPORT_TRANSLATIONS,
  ASSISTANT_TRANSLATIONS,
  SUBSCRIPTION_TRANSLATIONS,
  GENETICS_TRANSLATIONS,
  SPECIES_TRANSLATIONS,
  APP_EXTRAS_TRANSLATIONS,
  NURSERY_TRANSLATIONS,
];

ALL_SUB_DICTS.forEach((sub) => {
  if (!sub) return;
  Object.keys(sub).forEach((lang) => {
    const language = lang as Language;
    if (TRANSLATIONS[language]) {
      TRANSLATIONS[language] = {
        ...TRANSLATIONS[language],
        ...(sub[language] || {})
      };
    }
  });
});




