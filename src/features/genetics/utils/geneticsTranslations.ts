export function translateGenetics(language: Language, key: string, variables?: Variables): string {
  let text = dictionaries[language]?.[key] ?? fr[key] ?? key;
  Object.entries(variables ?? {}).forEach(([name, value]) => {
    text = text.split(`{${name}}`).join(String(value));
  });
  return text;
}
