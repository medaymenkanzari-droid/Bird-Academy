export const getPlatformTranslation = (lang: Language, key: string, variables?: Record<string, string | number>): string => {
  const dict = PLATFORM_TRANSLATIONS[lang] || PLATFORM_TRANSLATIONS['fr'];
  let text = dict[key] || PLATFORM_TRANSLATIONS['fr'][key] || String(key);

  if (variables) {
    Object.entries(variables).forEach(([k, val]) => {
      text = text.split(`{${k}}`).join(String(val));
    });
  }

  return text;
};
