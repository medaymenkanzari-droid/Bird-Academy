export function translateLicensing(lang: string, key: string, vars?: Record<string, any>): string {
  const dict = (LICENSING_TRANSLATIONS as any)[lang] || LICENSING_TRANSLATIONS.fr;
  let text = dict[key] || LICENSING_TRANSLATIONS.fr[key] || key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.split(`{${k}}`).join(String(v));
    });
  }
  return text;
}

